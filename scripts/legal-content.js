// Keep the offline legal viewer in sync with the documents shipped by the installer.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n?/g, '\n');
const content = {
  version: require('../package.json').version,
  license: read('LICENSE'),
  notices: read('THIRD_PARTY_NOTICES.txt')
};
const body = '// Generated by scripts/legal-content.js. Edit LICENSE or THIRD_PARTY_NOTICES.txt instead.\n' +
  'var DI = globalThis.DI || (globalThis.DI = {});\nDI.legal = ' + JSON.stringify(content, null, 2) + ';\n';
const file = 'src/legal.js';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(path.join(root, file)) || read(file) !== body) {
    console.error('Offline legal content is out of date: run node build-standalone.js');
    process.exit(1);
  }
  console.log('Offline legal content is up to date');
} else {
  fs.writeFileSync(path.join(root, file), body);
}
